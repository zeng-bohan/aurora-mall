import { chromium } from 'playwright'

const browser = await chromium.launch({ channel: 'chrome', headless: true })
const context = await browser.newContext({ viewport: { width: 1440, height: 900 } })
const page = await context.newPage()
const errors = []
page.on('console', (message) => {
  if (message.type() === 'error') errors.push(message.text())
})
page.on('pageerror', (error) => errors.push(error.message))

await page.goto('http://127.0.0.1:5173/login', { waitUntil: 'networkidle' })
await page.fill('input[autocomplete="username"]', 'zhouran')
await page.fill('input[autocomplete="current-password"]', 'Aurora123!')
await page.click('button[type="submit"]')
await page.waitForURL('http://127.0.0.1:5173/', { timeout: 15000 })

await page.goto('http://127.0.0.1:5173/products/5', { waitUntil: 'networkidle' })
await page.locator('.option', { hasText: '暖白' }).click()
await page.locator('.option', { hasText: '线性轴' }).click()
const price = await page.locator('.price-row__amount').innerText()
const skuText = await page.locator('.stock-line').innerText()
console.log('variant:', price, skuText)
if (!price.includes('749') || !skuText.includes('AUR-T75-WH-LN')) {
  throw new Error('SKU selection did not resolve to the expected variant')
}
await page.screenshot({ path: '../docs/screenshots/dtc-product-detail-1440.png', fullPage: true })
await page.getByRole('button', { name: '加入购物车' }).click()
await page.waitForTimeout(800)

await page.goto('http://127.0.0.1:5173/products/1', { waitUntil: 'networkidle' })
await page.getByRole('button', { name: '加入购物车' }).click()
await page.waitForTimeout(800)

await page.goto('http://127.0.0.1:5173/cart', { waitUntil: 'networkidle' })
console.log('cart lines:', await page.locator('.cart-line').count())
await page.screenshot({ path: '../docs/screenshots/dtc-cart-1440.png', fullPage: true })
await page.getByRole('button', { name: '去结算' }).click()
await page.waitForURL(/\/checkout/, { timeout: 15000 })
await page.waitForTimeout(800)
await page.locator('.radio-line', { hasText: '满 500 减 50' }).click()
await page.waitForTimeout(300)
const payable = await page.locator('.summary-total strong').innerText()
console.log('checkout payable:', payable)
await page.screenshot({ path: '../docs/screenshots/dtc-checkout-1440.png', fullPage: true })
await page.getByRole('button', { name: '提交订单' }).click()
await page.waitForURL(/\/orders\/\d+/, { timeout: 20000 })
await page.waitForTimeout(500)
const orderUrl = page.url()
console.log('order url:', orderUrl)
await page.getByRole('button', { name: '模拟支付' }).click()
for (let i = 0; i < 20; i += 1) {
  await page.waitForTimeout(1000)
  const hero = await page.locator('.status-hero h1').innerText()
  if (hero.includes('已支付')) break
}
console.log('status:', await page.locator('.status-hero h1').innerText())
await page.screenshot({ path: '../docs/screenshots/dtc-order-detail-1440.png', fullPage: true })

await page.getByRole('button', { name: '申请退款' }).click()
await page.waitForTimeout(800)
const dialog = page.locator('.el-dialog')
await dialog.getByText('Type 75 机械键盘').locator('..').locator('..').locator('input[type="checkbox"]').uncheck()
await page.waitForTimeout(800)
const refundAmount = await dialog.locator('.seckill-result strong').innerText()
console.log('refund amount:', refundAmount)
await dialog.locator('textarea').fill('桌面空间调整，先退掉充电器')
await page.screenshot({ path: '../docs/screenshots/dtc-refund-dialog.png' })
await dialog.getByRole('button', { name: '提交申请' }).click()
await page.waitForTimeout(1200)
console.log('refund rows:', await page.locator('.refund-line').count())
await page.screenshot({ path: '../docs/screenshots/dtc-order-refund-pending-1440.png', fullPage: true })
console.log('errors:', errors)
await context.storageState({ path: '../.taste-skill/user-state.json' })
console.log('saved state')
await browser.close()
